"""Source-code extraction (extractor ``code``): one section per symbol, with exact line ranges.

Runs in the extraction sandbox like the other worker extractors, so it imports the standard library
only (no tree-sitter: native code would need the OS-level gate). Per language:

- **Python**: ``ast``. A header section (module docstring, imports and any code before the first
  definition), then one section per top-level function or class, decorators, leading comments and
  docstring included. A class that does not fit one chunk is split by method (``Class.method``); the
  lines between methods stay with the class header or a neighbour. Top-level statements between
  definitions form their own sections (named after the names they assign). A file ``ast`` cannot
  parse falls back to line windows.
- **TypeScript, TSX, JavaScript**: a small scanner (strings, template literals, comments, regex
  literals, bracket depth) finds top-level declarations (``export function/const/class/interface/
  type/enum``, React components are ``export const``/``function``); a big class is split by member.
  Small neighbouring declarations are packed into one section. Anything the scanner cannot place
  falls back to line windows.
- **Shell, TOML, SQL, Dockerfile, CSS**: units at the format's natural boundaries (functions, tables,
  statements, build stages, rules), packed up to the chunk size.

Every section carries a ``CodeRef`` (language, path, symbol, 1-based inclusive ``start_line`` and
``end_line``, kind). Its text is a one-line header (``# path:start-end symbol``) and then the lines
verbatim, so the embedding sees the location. The section anchor is ``L<start>-L<end>``: the
chunker turns it into ``<source url>#L10-L42``, which on a commit-pinned GitHub blob URL is the exact
lines. Generated files (``Code generated``, ``DO NOT EDIT``, ``@generated`` in the first lines) and
minified ones (very long lines) yield no sections and a warning; a file with a NUL byte is binary.
"""

from __future__ import annotations

import ast
import re
from dataclasses import dataclass

from eap_knowledge.errors import ExtractionFailed
from eap_knowledge.model import CodeRef, Document, Section

CHARS_PER_TOKEN = 4
MAX_HEADING_CHARS = 128
MAX_SYMBOL_CHARS = 200
# Generated-file markers are looked for in the first lines only.
GENERATED_HEAD_LINES = 6
_GENERATED = re.compile(
    r"code generated|do not edit|@generated|this file (?:is|was) (?:auto-?)?generated|auto-?generated by",
    re.IGNORECASE,
)
# A line this long, or an average line this long in a file over 2 KB, is minified output.
MINIFIED_LINE = 2000
MINIFIED_MEAN = 200
MINIFIED_MEAN_MIN_CHARS = 2048
# A TS/JS declaration of at most this many characters (about chunker v2's 64-token minimum) is packed
# with its small neighbours instead of standing alone.
SMALL_UNIT_CHARS = 256
# A section is never planned below this many characters of code (a degenerate max_tokens).
MIN_CODE_CHARS = 256

_COMMENT_PREFIX = {
    "python": "#", "shell": "#", "toml": "#", "dockerfile": "#",
    "typescript": "//", "tsx": "//", "javascript": "//", "sql": "--",
}


@dataclass(frozen=True)
class _Unit:
    """A run of lines (1-based, inclusive) and the symbol it defines."""

    start: int
    end: int
    symbol: str | None
    pack: bool = True  # may be packed with small neighbours (false for the members of a split class)


def extract_code(
    content: str,
    language: str,
    *,
    path: str,
    kind: str = "code",
    title: str = "",
    source_url: str | None = None,
    max_tokens: int = 512,
    overlap_tokens: int = 0,
) -> Document:
    """Cut ``content`` into code sections (see the module docstring)."""
    if "\x00" in content:
        raise ExtractionFailed("unsupported_content", "a NUL byte: binary content")
    text = content.lstrip("﻿").replace("\r\n", "\n").replace("\r", "\n")
    lines = text.split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    skipped = _skip_reason(text, lines)
    if skipped is not None:
        return Document(title="", source_url=source_url or None, format="code", sections=(), warnings=(skipped,))
    ctx = _Ctx(language, path, kind, max(1, int(max_tokens)) * CHARS_PER_TOKEN, max(0, int(overlap_tokens)) * CHARS_PER_TOKEN)
    warnings: list[str] = []
    units: list[_Unit] | None = None
    try:
        if language == "python":
            units = _python_units(lines, ctx)
        elif language in ("typescript", "tsx", "javascript"):
            units = _ts_units(lines, ctx)
        elif language == "shell":
            units = _boundary_units(lines, ctx, _SHELL_BOUNDARY, _shell_symbol, comment="#")
        elif language == "toml":
            units = _boundary_units(lines, ctx, _TOML_BOUNDARY, lambda m: m.group(1), comment="#")
        elif language == "sql":
            units = _boundary_units(lines, ctx, _SQL_BOUNDARY, _sql_symbol, comment="--")
        elif language == "dockerfile":
            units = _boundary_units(lines, ctx, _DOCKER_BOUNDARY, _docker_symbol, comment="#")
        elif language == "css":
            units = _css_units(lines, ctx)
    except (SyntaxError, ValueError, RecursionError):
        warnings.append("parse_fallback")
        units = None
    if units is None:
        units = [_Unit(1, len(lines), None)] if lines else []
    sections = _sections(lines, units, ctx)
    extracted = sum(len("".join((s.heading + s.text).split())) for s in sections)
    return Document(
        title="", source_url=source_url or None, format="code", sections=tuple(sections),
        extracted_chars=extracted, warnings=tuple(warnings),
    )


def _skip_reason(text: str, lines: list[str]) -> str | None:
    if not text.strip():
        return None
    if any(_GENERATED.search(line) for line in lines[:GENERATED_HEAD_LINES]):
        return "generated_skipped"
    longest = max((len(line) for line in lines), default=0)
    if longest > MINIFIED_LINE:
        return "minified_skipped"
    if len(text) > MINIFIED_MEAN_MIN_CHARS and len(text) / max(1, len(lines)) > MINIFIED_MEAN:
        return "minified_skipped"
    return None


@dataclass(frozen=True)
class _Ctx:
    language: str
    path: str
    kind: str
    max_chars: int
    overlap_chars: int

    def avail(self, symbol_len: int = 40) -> int:
        """Characters of code one section may hold: the chunk size minus the embed prefix (the
        heading line) and the header line, which both name the path, range and symbol."""
        header = len(self.path) + symbol_len + 24
        return max(MIN_CODE_CHARS, self.max_chars - 2 * min(header, MAX_HEADING_CHARS + 32))


# --- sections ------------------------------------------------------------------------------------


def _clip(text: str, limit: int) -> str:
    return text if len(text) <= limit else text[: limit - 1] + "…"


def _short_path(path: str, limit: int = 72) -> str:
    return path if len(path) <= limit else "…" + path[-(limit - 1) :]


def _header_line(ctx: _Ctx, start: int, end: int, symbol: str | None) -> str:
    label = f"{ctx.path}:{start}-{end}" + (f" {symbol}" if symbol else "")
    prefix = _COMMENT_PREFIX.get(ctx.language)
    return f"{prefix} {label}" if prefix else f"/* {label} */"


def _trim(lines: list[str], start: int, end: int) -> tuple[int, int]:
    while start <= end and not lines[start - 1].strip():
        start += 1
    while end >= start and not lines[end - 1].strip():
        end -= 1
    return start, end


def _sections(lines: list[str], units: list[_Unit], ctx: _Ctx) -> list[Section]:
    out: list[Section] = []
    for unit in units:
        start, end = _trim(lines, unit.start, unit.end)
        if start > end:
            continue
        symbol = _clip(unit.symbol, MAX_SYMBOL_CHARS) if unit.symbol else None
        avail = ctx.avail(len(symbol or "") + 12)
        windows = _windows(lines, start, end, avail, ctx.overlap_chars)
        for index, (ws, we) in enumerate(windows, 1):
            label = symbol
            if len(windows) > 1:
                label = f"{symbol or '<code>'} (part {index}/{len(windows)})"
            body = "\n".join(lines[ws - 1 : we])
            if not body.strip():
                continue
            header = _header_line(ctx, ws, we, label)
            heading = _clip(f"{_short_path(ctx.path)}:{ws}-{we}" + (f" {label}" if label else ""), MAX_HEADING_CHARS)
            out.append(
                Section(
                    heading_path=(),
                    heading=heading,
                    level=0,
                    text=f"{header}\n{body}",
                    anchor=f"L{ws}-L{we}",
                    code=CodeRef(
                        language=ctx.language, path=ctx.path[:1024], start_line=ws, end_line=we,
                        symbol=_clip(label, 256) if label else None, kind=ctx.kind,
                    ),
                )
            )
    return out


def _windows(lines: list[str], start: int, end: int, avail: int, overlap_chars: int) -> list[tuple[int, int]]:
    """Line windows covering ``start..end``, each at most ``avail`` characters (a single longer line
    stands alone). A window ends at a blank line when one lies in its last 40 %; the next window
    starts ``overlap_chars`` of whole lines before the end of the previous one."""
    total = sum(len(lines[i - 1]) + 1 for i in range(start, end + 1))
    if total <= avail:
        return [(start, end)]
    overlap_chars = min(overlap_chars, avail // 4)
    windows: list[tuple[int, int]] = []
    first = start
    while first <= end:
        size, last = 0, first
        while last <= end and (last == first or size + len(lines[last - 1]) + 1 <= avail):
            size += len(lines[last - 1]) + 1
            last += 1
        last -= 1  # the final line that fits
        if last < end:
            floor = first + int((last - first) * 0.6)
            blank = next((i for i in range(last, floor, -1) if not lines[i - 1].strip()), None)
            if blank is not None and blank > first:
                last = blank
        windows.append((first, last))
        if last >= end:
            break
        back, taken = last, 0
        while back > first + 1 and taken + len(lines[back - 1]) + 1 <= overlap_chars:
            taken += len(lines[back - 1]) + 1
            back -= 1
        first = back + 1 if back < last else last + 1
        first = max(first, windows[-1][0] + 1)
    return windows


def _pack(lines: list[str], units: list[_Unit], ctx: _Ctx) -> list[_Unit]:
    """Merge adjacent units while the run stays within one section; the run's symbol lists its names."""
    avail = ctx.avail()
    out: list[_Unit] = []
    run: list[_Unit] = []

    def flush() -> None:
        if not run:
            return
        names = [u.symbol for u in run if u.symbol]
        symbol = ", ".join(names[:6]) + (f" (+{len(names) - 6})" if len(names) > 6 else "") if names else None
        out.append(_Unit(run[0].start, run[-1].end, symbol))
        run.clear()

    for unit in units:
        if run and _span_chars(lines, run[0].start, unit.end) > avail:
            flush()
        run.append(unit)
    flush()
    return out


def _span_chars(lines: list[str], start: int, end: int) -> int:
    return sum(len(lines[i - 1]) + 1 for i in range(start, end + 1))


def _with_comments(lines: list[str], start: int, floor: int, marker: str) -> int:
    """Move ``start`` up over the comment lines directly above it (no blank line between), not past ``floor``."""
    while start - 1 >= floor and lines[start - 2].lstrip().startswith(marker):
        start -= 1
    return start


# --- Python --------------------------------------------------------------------------------------


@dataclass(frozen=True)
class _Seg:
    kind: str  # "def", "class", "loose"
    start: int
    end: int
    node: ast.AST | None
    names: tuple[str, ...] = ()
    imports: bool = False


def _node_start(node: ast.stmt) -> int:
    decorators = getattr(node, "decorator_list", None) or []
    return min([d.lineno for d in decorators] + [node.lineno])


def _python_units(lines: list[str], ctx: _Ctx) -> list[_Unit]:
    tree = ast.parse("\n".join(lines))
    return _python_partition(lines, tree.body, 1, len(lines), "", ctx, module=True)


def _assigned_names(node: ast.stmt) -> tuple[str, ...]:
    targets: list[ast.expr] = []
    if isinstance(node, ast.Assign):
        targets = list(node.targets)
    elif isinstance(node, (ast.AnnAssign, ast.AugAssign)):
        targets = [node.target]
    return tuple(t.id for t in targets if isinstance(t, ast.Name))


def _python_partition(
    lines: list[str], nodes: list[ast.stmt], lo: int, hi: int, prefix: str, ctx: _Ctx, *, module: bool
) -> list[_Unit]:
    """Units for the statements ``nodes`` that lie in lines ``lo..hi``: definitions one each, runs of
    other statements together, anything before the first statement as a head."""
    segs: list[_Seg] = []
    prev_end = lo - 1
    for node in nodes:
        start = _with_comments(lines, _node_start(node), prev_end + 1, "#")
        end = node.end_lineno or node.lineno
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            segs.append(_Seg("def", start, end, node))
        elif isinstance(node, ast.ClassDef):
            segs.append(_Seg("class", start, end, node))
        else:
            names = _assigned_names(node)
            is_import = isinstance(node, (ast.Import, ast.ImportFrom))
            last = segs[-1] if segs else None
            if last is not None and last.kind == "loose":
                segs[-1] = _Seg("loose", last.start, end, None, last.names + names, last.imports or is_import)
            else:
                segs.append(_Seg("loose", start, end, None, names, is_import))
        prev_end = end
    units: list[_Unit] = []
    first_start = segs[0].start if segs else hi + 1
    head_lines = [i for i in range(lo, first_start) if lines[i - 1].strip()]
    head_symbol = "<module>" if module else (prefix or None)
    if head_lines:
        head_end = first_start - 1
        if segs and segs[0].kind == "loose":  # the head and the first loose run are one section
            seg0 = segs.pop(0)
            stop0 = segs[0].start - 1 if segs else hi
            units.append(_Unit(lo, stop0, "<module>" if module else prefix or None))
        elif segs:
            units.append(_Unit(lo, head_end, head_symbol))
        else:
            units.append(_Unit(lo, hi, head_symbol))
    for index, seg in enumerate(segs):
        stop = segs[index + 1].start - 1 if index + 1 < len(segs) else hi
        start = seg.start
        if seg.kind == "def":
            name = seg.node.name  # type: ignore[union-attr]
            units.append(_Unit(start, stop, f"{prefix}.{name}" if prefix else name))
        elif seg.kind == "class":
            name = seg.node.name  # type: ignore[union-attr]
            qual = f"{prefix}.{name}" if prefix else name
            if _span_chars(lines, start, stop) <= ctx.avail(len(qual)) or not seg.node.body:  # type: ignore[union-attr]
                units.append(_Unit(start, stop, qual))
            else:
                units.extend(
                    _python_partition(lines, seg.node.body, start, stop, qual, ctx, module=False)  # type: ignore[union-attr]
                )
        else:
            if seg.imports:
                symbol = "<module>" if module else prefix or None
            elif seg.names:
                shown = ", ".join(f"{prefix}.{n}" if prefix else n for n in seg.names[:3])
                symbol = shown + ("…" if len(seg.names) > 3 else "")
            else:
                symbol = "<module-level>" if module else prefix or None
            units.append(_Unit(start, stop, symbol))
    return units


# --- TypeScript / TSX / JavaScript ---------------------------------------------------------------

_REGEX_PRECEDERS = frozenset("(,=:[!&|?{};+-*%<>~^")
_REGEX_AFTER_KEYWORD = re.compile(r"(?:return|typeof|case|do|else|in|of|void|delete|throw|new|yield|await)$")


def _scan(lines: list[str], *, line_comments: bool, regex: bool) -> tuple[list[int], list[bool]]:
    """Per line: the bracket depth at the start of the line, and whether the line starts inside a block
    comment, a template literal or a multi-line string (so it can never begin a declaration)."""
    depths: list[int] = []
    inside: list[bool] = []
    depth = 0
    block = False  # in /* ... */
    templates: list[int] = []  # for each open template literal: the bracket depth at its `${`, or -1 in text
    in_template_text = False
    for line in lines:
        depths.append(depth)
        inside.append(block or in_template_text)
        i, n = 0, len(line)
        last = ""  # the last significant character, for the regex heuristic
        word = ""
        while i < n:
            c = line[i]
            if block:
                end = line.find("*/", i)
                if end < 0:
                    i = n
                else:
                    block, i = False, end + 2
                continue
            if in_template_text:
                if c == "\\":
                    i += 2
                elif c == "`":
                    in_template_text = False
                    templates.pop() if templates else None
                    i += 1
                    last = "a"
                elif c == "$" and line.startswith("${", i):
                    in_template_text = False
                    templates.append(depth)
                    depth += 1
                    i += 2
                    last = "{"
                else:
                    i += 1
                continue
            if c == "/" and line.startswith("/*", i):
                block, i = True, i + 2
                continue
            if line_comments and c == "/" and line.startswith("//", i):
                break
            if c in "'\"":
                j = i + 1
                while j < n and line[j] != c:
                    j += 2 if line[j] == "\\" else 1
                i = j + 1  # a string never spans lines here (an unclosed one ends with the line)
                last = "a"
                word = ""
                continue
            if c == "`":
                in_template_text = True
                templates.append(-1)
                i += 1
                continue
            if regex and c == "/" and (last == "" or last in _REGEX_PRECEDERS or _REGEX_AFTER_KEYWORD.search(word)):
                j, in_class = i + 1, False
                while j < n and (in_class or line[j] != "/"):
                    if line[j] == "\\":
                        j += 1
                    elif line[j] == "[":
                        in_class = True
                    elif line[j] == "]":
                        in_class = False
                    j += 1
                if j < n:  # a closed literal on this line; otherwise it was a division
                    i, last, word = j + 1, "a", ""
                    continue
            if c in "{([":
                depth += 1
            elif c in "})]":
                depth = max(0, depth - 1)
                if c == "}" and templates and templates[-1] == depth:
                    in_template_text = True  # back into the template's text after `${...}`
                    i += 1
                    continue
            if c.isalnum() or c in "_$":
                word += c
            elif not c.isspace():
                word = ""
            if not c.isspace():
                last = c
            i += 1
    return depths, inside


_TS_DECL = re.compile(
    r"^(?:export\s+)?(?:default\s+)?(?:declare\s+)?(?:abstract\s+)?(?:async\s+)?"
    r"(function\s*\*?|class|interface|type|enum|namespace|module|const|let|var)\b\s*([A-Za-z_$][\w$]*)?"
)
_TS_DEFAULT_EXPR = re.compile(r"^export\s+default\b")
_TS_MEMBER = re.compile(
    r"^(?:(?:public|private|protected|static|readonly|override|abstract|declare|async|get|set|accessor)\s+)*"
    r"(?:\*\s*)?(#?[A-Za-z_$][\w$]*|\[[^\]]+\]|'[^']*'|\"[^\"]*\")"
)
_CONTINUATION_START = ("}", ")", "]", ".", ",", "?", ":", "|", "&", "+", "-", "*", "=", ">", ";")


def _is_comment(line: str) -> bool:
    s = line.lstrip()
    return s.startswith(("//", "/*", "*"))


def _ts_units(lines: list[str], ctx: _Ctx) -> list[_Unit]:
    line_comments = True
    depths, inside = _scan(lines, line_comments=line_comments, regex=True)
    n = len(lines)
    starts: list[int] = []  # 1-based unit starts
    for i in range(n):
        line = lines[i]
        if not line.strip() or inside[i] or depths[i] != 0 or line[0].isspace():
            continue
        if line.startswith(_CONTINUATION_START) and not line.startswith(("//", "/*")):
            continue
        if i > 0 and _is_comment(lines[i - 1]) and lines[i - 1].strip():
            continue  # a comment run attaches to the line below it
        if i > 0 and lines[i - 1].startswith("@") and depths[i - 1] == 0 and not _TS_DECL.match(lines[i - 1]):
            continue  # a decorator belongs to the declaration below it
        starts.append(i + 1)
    if not starts:
        return [_Unit(1, n, None)] if n else []
    raw: list[tuple[int, int]] = []
    for k, s in enumerate(starts):
        raw.append((s, starts[k + 1] - 1 if k + 1 < len(starts) else n))
    if starts[0] > 1:
        raw.insert(0, (1, starts[0] - 1))
    units: list[_Unit] = []
    for s, e in raw:
        code_line = next((lines[i - 1] for i in range(s, e + 1) if lines[i - 1].strip() and not _is_comment(lines[i - 1]) and not lines[i - 1].startswith("@")), "")
        symbol, kind = _ts_symbol(code_line)
        if kind == "class" and _span_chars(lines, s, e) > ctx.avail(len(symbol or "") + 12):
            units.extend(_ts_class_units(lines, depths, inside, s, e, symbol or "<class>", ctx))
        else:
            units.append(_Unit(s, e, symbol if kind else None))
    return _pack_small(lines, units, ctx)


def _ts_symbol(code_line: str) -> tuple[str | None, str]:
    text = code_line.strip()
    m = _TS_DECL.match(text)
    if m:
        keyword = m.group(1).replace(" ", "").rstrip("*")
        name = m.group(2)
        if keyword in ("const", "let", "var") and name is None:  # destructuring
            return _clip(text.split("=", 1)[0].strip().removeprefix("export").strip()[len(keyword):].strip(), 60) or None, "decl"
        if name is None and keyword in ("function",):
            return "default" if _TS_DEFAULT_EXPR.match(text) else "<anonymous>", "decl"
        return name, "class" if keyword == "class" else "decl"
    if _TS_DEFAULT_EXPR.match(text):
        return "default", "decl"
    return None, ""


def _ts_class_units(
    lines: list[str], depths: list[int], inside: list[bool], start: int, end: int, cls: str, ctx: _Ctx
) -> list[_Unit]:
    """A class too big for one section, cut at its members (lines at bracket depth 1 that open one)."""
    bounds: list[int] = []
    for i in range(start, end):  # 0-based index i is line i+1; skip the class line itself
        line = lines[i]
        s = line.strip()
        if not s or inside[i] or depths[i] != 1 or not line[0].isspace() or i + 1 == start:
            continue
        if s.startswith(_CONTINUATION_START) and not s.startswith(("//", "/*")):
            continue
        if _is_comment(lines[i - 1]) and lines[i - 1].strip():
            continue
        prev = next((lines[j].strip() for j in range(i - 1, start - 1, -1) if lines[j].strip()), "")
        if prev.endswith((",", "=", "(", "&&", "||", "?", ":", "=>")):
            continue
        if prev.startswith("@") and not prev.endswith(("{", ";")):
            continue
        bounds.append(i + 1)
    if not bounds:
        return [_Unit(start, end, cls, pack=False)]
    out = [_Unit(start, bounds[0] - 1, cls, pack=False)]
    for k, b in enumerate(bounds):
        stop = bounds[k + 1] - 1 if k + 1 < len(bounds) else end
        code = next((lines[i - 1].strip() for i in range(b, stop + 1) if lines[i - 1].strip() and not _is_comment(lines[i - 1]) and not lines[i - 1].strip().startswith("@")), "")
        m = _TS_MEMBER.match(code)
        out.append(_Unit(b, stop, f"{cls}.{m.group(1)}" if m else cls, pack=False))
    return out


def _pack_small(lines: list[str], units: list[_Unit], ctx: _Ctx) -> list[_Unit]:
    """Pack neighbouring units that are each small (imports, type aliases, constants) into runs; a
    unit above the small threshold stands alone (and may be split into windows later)."""
    small = min(ctx.avail() // 3, SMALL_UNIT_CHARS)
    out: list[_Unit] = []
    run: list[_Unit] = []

    def flush() -> None:
        if run:
            out.extend(_pack(lines, run, ctx))
            run.clear()

    for unit in units:
        if unit.pack and _span_chars(lines, unit.start, unit.end) <= small:
            run.append(unit)
        else:
            flush()
            out.append(unit)
    flush()
    return out


# --- shell, TOML, SQL, Dockerfile, CSS -----------------------------------------------------------

_SHELL_BOUNDARY = re.compile(r"^(?:function\s+([\w:.-]+)|([\w:.-]+)\s*\(\s*\))\s*(?:\{|$)")
_TOML_BOUNDARY = re.compile(r"^\s*(\[\[?[^\]\n]+\]\]?)")
_SQL_BOUNDARY = re.compile(
    r"^(?:create|alter|drop|insert|update|delete|select|with|grant|revoke|comment|truncate|do|begin|set)\b.*", re.IGNORECASE
)
_DOCKER_BOUNDARY = re.compile(r"^FROM\b(.*)", re.IGNORECASE)


def _shell_symbol(m: re.Match[str]) -> str:
    return m.group(1) or m.group(2)


def _sql_symbol(m: re.Match[str]) -> str:
    return _clip(" ".join(m.group(0).split()), 60).rstrip("(;, ")


def _docker_symbol(m: re.Match[str]) -> str:
    parts = m.group(1).split()
    alias = next((parts[i + 1] for i, p in enumerate(parts[:-1]) if p.lower() == "as"), None)
    image = next((p for p in parts if not p.startswith("--")), "")
    return f"stage {alias}" if alias else f"FROM {image}".strip()


def _boundary_units(lines: list[str], ctx: _Ctx, pattern: re.Pattern[str], symbol_of, *, comment: str) -> list[_Unit]:
    starts: list[tuple[int, str]] = []
    for i, line in enumerate(lines):
        m = pattern.match(line)
        if m is not None and not (line[:1].isspace() and pattern is not _TOML_BOUNDARY):
            starts.append((i + 1, symbol_of(m)))
    if not starts:
        return [_Unit(1, len(lines), None)] if lines else []
    units: list[_Unit] = []
    previous_end = 0
    bounds: list[tuple[int, str]] = []
    for s, symbol in starts:
        bounds.append((_with_comments(lines, s, previous_end + 1 if bounds else 1, comment), symbol))
    if bounds[0][0] > 1:
        units.append(_Unit(1, bounds[0][0] - 1, None))
    for k, (s, symbol) in enumerate(bounds):
        units.append(_Unit(s, bounds[k + 1][0] - 1 if k + 1 < len(bounds) else len(lines), symbol))
    return _pack(lines, units, ctx)


def _css_units(lines: list[str], ctx: _Ctx) -> list[_Unit]:
    depths, inside = _scan(lines, line_comments=False, regex=False)
    units: list[_Unit] = []
    starts: list[int] = []
    for i, line in enumerate(lines):
        if not line.strip() or inside[i] or depths[i] != 0 or line[0].isspace() or line.startswith(("}", "*")):
            continue
        if i > 0 and lines[i - 1].strip().endswith("*/"):
            continue
        starts.append(i + 1)
    if not starts:
        return [_Unit(1, len(lines), None)] if lines else []
    for k, s in enumerate(starts):
        e = starts[k + 1] - 1 if k + 1 < len(starts) else len(lines)
        head = lines[s - 1].split("{", 1)[0].strip()
        units.append(_Unit(s, e, _clip(head, 60) or None))
    if starts[0] > 1:
        units.insert(0, _Unit(1, starts[0] - 1, None))
    return _pack(lines, units, ctx)
